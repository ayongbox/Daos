import type { SchemaApp, SchemaTable } from '@daos/metadata';
import { createForm } from './FormDesigner';
import { createMenu, createView } from './ViewDesigner';

export interface ScaffoldResult {
  app: SchemaApp;
  created: string[];
}

/**
 * 为数据表补齐默认表单、默认列表和默认菜单。
 *
 * <p>只补齐缺失结构，不覆盖已有表单/视图配置；表没有字段时不生成任何内容。</p>
 */
export function scaffoldTablePage(app: SchemaApp, table: SchemaTable): ScaffoldResult {
  const activeFields = table.fields.filter((field) => !field.deleted);
  if (activeFields.length === 0) {
    return { app, created: [] };
  }

  const created: string[] = [];
  let forms = app.forms;
  let views = app.views ?? [];
  let menus = app.menus ?? [];

  let form = forms.find((item) => !item.deleted && item.tableId === table.id) ?? null;
  if (!form) {
    const base = createForm(app, table, `${table.displayName}表单`);
    form = { ...base, ext: { ...base.ext, autoGenerated: true } };
    forms = [...forms, form];
    created.push(`表单「${form.displayName}」`);
  }

  let view = views.find((item) => !item.deleted && item.tableId === table.id) ?? null;
  if (!view) {
    const base = createView(app, table);
    view = { ...base, ext: { ...base.ext, autoGenerated: true } };
    views = [...views, view];
    created.push(`列表「${view.displayName}」`);
  }

  const boundView = view;
  const boundForm = form;
  let menu = menus.find(
    (item) => !item.deleted && item.menuType === 'VIEW' && item.targetId === boundView.id
  ) ?? null;
  if (!menu) {
    menu = createMenu(app, 'VIEW', {
      code: `menu_${table.code}`,
      targetId: boundView.id,
      displayName: table.displayName,
      sortOrder: menus.length,
      ext: {
        autoGenerated: true,
        formId: boundForm.id,
        layout: {
          blocks: [
            {
              id: `page_${table.code}`,
              type: 'list',
              title: table.displayName,
              viewId: boundView.id
            }
          ]
        }
      }
    });
    menus = [...menus, menu];
    created.push(`菜单「${menu.displayName}」`);
  }

  return { app: { ...app, forms, views, menus }, created };
}
